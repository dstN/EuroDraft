/**
 * Calculates accurate tournament OVR for any player.
 */
export function calculateTournamentOVR(
  playerName: string,
  year: number,
  country: string,
  basePosition: 'Goalkeeper' | 'Defender' | 'Midfielder' | 'Forward',
  caps: number,
  goals: number,
  shirtNumber: number | null
): number {
  const norm = normalizeRatingKey(playerName)

  // 1. Year-specific exact match (e.g. 'cristiano ronaldo@2004' -> 82)
  const exactKey = `${norm}@${year}`
  if (YEAR_SPECIFIC_RATINGS[exactKey] !== undefined) {
    return YEAR_SPECIFIC_RATINGS[exactKey]!
  }

  // 2. Fuzzy match in year-specific ratings
  if (norm.length >= 4) {
    for (const [key, rating] of Object.entries(YEAR_SPECIFIC_RATINGS)) {
      const [namePart, yearPart] = key.split('@')
      if (yearPart === String(year)) {
        if (norm === namePart || norm.includes(namePart!) || namePart!.includes(norm)) {
          return rating
        }
      }
    }
  }

  // 3. Fallback: Calibrated algorithm based on nation strength tier, caps, goals, and shirt number
  const tier = NATION_TIER_MAP[country.toLowerCase()] ?? 2

  // Base OVR by nation tier
  let baseOvr = tier === 1 ? 78 : tier === 2 ? 75 : 72

  // Starter heuristic: low shirt number (1-11) or high caps (>15)
  const isStarter = (shirtNumber !== null && shirtNumber >= 1 && shirtNumber <= 11) || (caps >= 20)
  if (isStarter) {
    baseOvr += 2
  }

  // Caps experience bonus (up to +4)
  const capsBonus = Math.min(4, Math.floor((caps || 5) / 18))
  baseOvr += capsBonus

  // Goal scorer bonus for forwards and attacking mids
  if (goals > 0) {
    const goalBonus = basePosition === 'Forward'
      ? Math.min(3, Math.floor(goals / 8))
      : Math.min(2, Math.floor(goals / 5))
    baseOvr += goalBonus
  }

  // Uncapped or very young reserve penalty (-2)
  if (caps <= 2 && (shirtNumber === null || shirtNumber > 18)) {
    baseOvr -= 2
  }

  // Final bounds
  const minOvr = tier === 1 ? 73 : tier === 2 ? 69 : 66
  const maxOvr = tier === 1 ? 84 : tier === 2 ? 82 : 79

  return Math.min(maxOvr, Math.max(minOvr, baseOvr))
}
